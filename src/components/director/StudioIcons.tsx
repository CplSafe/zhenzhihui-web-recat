function shape(item: Shape, index: number): React.ReactNode {
  const attributes = Object.fromEntries(
    Object.entries(item.attrs).map(([key, value]) => [
      key.replace(/-([a-z])/g, (_, letter: string) => letter.toUpperCase()),
      value,
    ]),
  )
  return createElement(item.tag, { ...attributes, key: index }, ...item.children.map(shape))
}
