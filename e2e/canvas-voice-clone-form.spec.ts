import { expect, test } from '@playwright/test'
import { setupVoiceLibrary } from './fixtures/canvas-voice-library'
import { expectNoUnexpectedApi } from './fixtures/strict-authenticated-app'

function tenSecondWav(): Buffer {
  const wav = Buffer.alloc(44 + 24000 * 10 * 2)
  wav.write('RIFF', 0)
  wav.writeUInt32LE(wav.length - 8, 4)
  wav.write('WAVEfmt ', 8)
  wav.writeUInt32LE(16, 16)
  wav.writeUInt16LE(1, 20)
  wav.writeUInt16LE(1, 22)
  wav.writeUInt32LE(24000, 24)
  wav.writeUInt32LE(48000, 28)
  wav.writeUInt16LE(2, 32)
  wav.writeUInt16LE(16, 34)
  wav.write('data', 36)
  wav.writeUInt32LE(wav.length - 44, 40)
  return wav
}

for (const width of [1440, 768, 390]) {
  test(`音色复刻分区、名称授权校验和文件限制 ${width}px`, async ({ page }, testInfo) => {
    await page.setViewportSize({ width, height: 1000 })
    const { modal, createRequests, errors, state } = await setupVoiceLibrary(page)
    await modal.getByRole('button', { name: '我的音色', exact: true }).click()
    await modal.getByRole('button', { name: '添加音色', exact: true }).click()
    const form = modal.getByRole('form', { name: '创建音色表单' })
    for (const name of ['基础信息', '现场录音', '上传音频']) {
      await expect(form.getByRole('region', { name, exact: true })).toHaveCount(1)
    }
    await expect(form.getByRole('combobox', { name: '复刻供应商' })).toHaveValue('minimax')
    const submit = form.getByRole('button', { name: '提交复刻', exact: true })
    const name = form.getByRole('textbox', { name: '音色名称', exact: true })
    await name.fill('   ')
    await name.blur()
    await expect(name).toHaveAttribute('aria-invalid', 'true')
    await expect(form.getByRole('alert')).toHaveText('请输入音色名称')
    await name.fill('品牌旁白')
    await expect(form.getByRole('alert')).toHaveCount(0)
    const more = form.locator('summary').filter({ hasText: '更多信息（可选）' })
    await more.click()
    const description = form.getByRole('textbox', { name: '描述', exact: true })
    await description.fill('温柔自然的品牌旁白')
    await form.getByRole('textbox', { name: '语种', exact: true }).fill('中文')
    await form.getByRole('textbox', { name: '声音性别描述', exact: true }).fill('女声')
    await form.getByRole('textbox', { name: '标签（逗号分隔）', exact: true }).fill('温柔，旁白')
    await more.scrollIntoViewIfNeeded()
    await page.screenshot({ path: testInfo.outputPath(`optional-information-${width}.png`) })
    const fields = description.locator('..').locator('..')
    expect(await fields.evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true)
    await more.focus()
    await page.keyboard.press('Enter')
    await expect(description).not.toBeVisible()
    await page.keyboard.press('Enter')
    await expect(description).toHaveValue('温柔自然的品牌旁白')
    await expect(form.getByRole('textbox', { name: '语种', exact: true })).toHaveValue('中文')
    await more.click()

    await name.scrollIntoViewIfNeeded()
    await page.screenshot({ path: testInfo.outputPath(`clone-form-${width}.png`) })
    await expect(submit).toBeDisabled()
    const consent = form.getByRole('checkbox', { name: '我确认声音属于本人或已获得音色复刻授权' })
    await consent.check()
    await expect(submit).toBeDisabled()
    const upload = form.getByLabel('上传训练录音')
    await upload.setInputFiles({ name: 'invalid.txt', mimeType: 'text/plain', buffer: Buffer.from('not audio') })
    await expect(form.getByRole('alert')).toContainText('20 MiB 以内')
    await expect(submit).toBeDisabled()
    await upload.setInputFiles({ name: 'large.wav', mimeType: 'audio/wav', buffer: Buffer.alloc(20 * 1024 * 1024 + 1) })
    await expect(form.getByRole('alert')).toContainText('20 MiB 以内')
    await expect(submit).toBeDisabled()
    const transfer = await page.evaluateHandle((base64) => {
      const bytes = Uint8Array.from(atob(base64), (character) => character.charCodeAt(0))
      const data = new DataTransfer()
      data.items.add(new File([bytes], '品牌旁白.wav', { type: 'audio/wav' }))
      return data
    }, tenSecondWav().toString('base64'))
    await form.getByRole('button', { name: /更换音频/ }).dispatchEvent('dragover', { dataTransfer: transfer })
    await expect(form.getByText('松开即可选择文件')).toBeVisible()
    await form.getByRole('button', { name: /更换音频/ }).dispatchEvent('drop', { dataTransfer: transfer })
    await transfer.dispose()
    await expect(form.getByRole('alert')).toHaveCount(0)
    await expect(form.getByText(/当前采用：上传音频/)).toContainText('10.0 秒')
    await expect(consent).not.toBeChecked()
    await expect(submit).toBeDisabled()
    await consent.check()
    await expect(submit).toBeEnabled()
    await name.fill(' ')
    await expect(submit).toBeDisabled()
    await name.fill('品牌旁白')
    await submit.scrollIntoViewIfNeeded()
    await page.screenshot({ path: testInfo.outputPath(`clone-ready-${width}.png`) })
    expect(await form.evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true)
    await form.getByRole('button', { name: '移除音频', exact: true }).click()
    await expect(form.getByLabel('试听训练录音')).toHaveCount(0)
    await expect(submit).toBeDisabled()
    const chooser = page.waitForEvent('filechooser')
    await form.getByRole('button', { name: /选择音频文件/ }).click()
    await (await chooser).setFiles({ name: '重新选择.wav', mimeType: 'audio/wav', buffer: tenSecondWav() })
    await expect(form.getByLabel('试听训练录音')).toBeVisible()
    await expect(consent).not.toBeChecked()
    expect(createRequests).toHaveLength(0)
    expect(errors).toEqual([])
    expectNoUnexpectedApi(state)
  })
}
